// Builds the 1° land/sea bitmask shared by client and server, and copies the
// high-detail coastline used by the map when zoomed in.
//   node scripts/build-geo.mjs [--debug]
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const W = 360, H = 180, SUB = 3;
const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-50m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const geom = land.features ? land.features[0].geometry : land.geometry;

// Unwrap rings so they are continuous across the antimeridian, then keep bbox per ring.
const rings = [];
for (const poly of geom.coordinates) {
  for (let r = 0; r < poly.length; r++) {
    const src = poly[r];
    const pts = [];
    let off = 0;
    for (let i = 0; i < src.length; i++) {
      let [x, y] = src[i];
      if (i > 0) {
        const px = src[i - 1][0];
        if (x - px > 180) off -= 360;
        else if (px - x > 180) off += 360;
      }
      pts.push([x + off, y]);
    }
    let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
    for (const [x, y] of pts) {
      if (x < minX) minX = x; if (x > maxX) maxX = x;
      if (y < minY) minY = y; if (y > maxY) maxY = y;
    }
    rings.push({ pts, minX, maxX, minY, maxY });
  }
}

function inRing(ring, x, y) {
  if (x < ring.minX || x > ring.maxX || y < ring.minY || y > ring.maxY) return false;
  let inside = false;
  const p = ring.pts;
  for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
    const [xi, yi] = p[i], [xj, yj] = p[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

// Even-odd across all rings (holes are separate rings) handles lakes correctly.
function isLandPoint(lon, lat) {
  let count = 0;
  for (const ring of rings) {
    for (const dx of [0, 360, -360]) if (inRing(ring, lon + dx, lat)) count++;
  }
  return count % 2 === 1;
}

const bits = new Uint8Array((W * H) / 8);
const set = (c, r, v) => {
  const i = r * W + c;
  if (v) bits[i >> 3] |= 1 << (i & 7);
  else bits[i >> 3] &= ~(1 << (i & 7));
};
const get = (c, r) => { const i = r * W + c; return (bits[i >> 3] >> (i & 7)) & 1; };

for (let r = 0; r < H; r++) {
  const lat0 = 90 - r - 1;
  for (let c = 0; c < W; c++) {
    const lon0 = -180 + c;
    let n = 0;
    for (let a = 0; a < SUB; a++) for (let b = 0; b < SUB; b++) {
      if (isLandPoint(lon0 + (b + 0.5) / SUB, lat0 + (a + 0.5) / SUB)) n++;
    }
    set(c, r, n * 2 > SUB * SUB);
  }
}

const cell = (lat, lon) => [Math.floor(lon + 180), Math.floor(90 - lat)];
// Narrow straits and canals that the 1° raster closes: force them to water.
const carve = [
  // Panama canal
  [9.5, -80.5], [8.5, -79.5], [9.5, -79.5],
  // Suez canal + Gulf of Suez
  [31.5, 32.5], [30.5, 32.5], [29.5, 32.5], [28.5, 33.5], [27.5, 33.5],
  // Gibraltar
  [36.5, -5.5], [35.5, -5.5], [36.5, -6.5], [35.5, -4.5],
  // Bosporus / Dardanelles
  [40.5, 26.5], [40.5, 27.5], [41.5, 28.5], [41.5, 29.5],
  // Malacca / Singapore
  [1.5, 103.5], [1.5, 104.5], [2.5, 101.5], [3.5, 100.5],
  // Bering
  [65.5, -168.5], [65.5, -169.5], [66.5, -168.5],
  // Hormuz
  [26.5, 56.5], [26.5, 55.5], [25.5, 56.5],
  // Bab-el-Mandeb
  [12.5, 43.5], [13.5, 42.5],
  // Danish straits / Kattegat
  [56.5, 11.5], [55.5, 11.5], [55.5, 12.5],
];
for (const [lat, lon] of carve) { const [c, r] = cell(lat, lon); set(c, r, 0); }

if (process.argv.includes('--debug')) {
  const show = (name, lat, lon, span = 8) => {
    console.log(`\n${name} (${lat},${lon})`);
    for (let la = lat + span; la >= lat - span; la--) {
      let line = '';
      for (let lo = lon - span * 2; lo <= lon + span * 2; lo++) {
        const [c, r] = cell(la + 0.5, lo + 0.5);
        line += get((c + W) % W, r) ? '#' : '.';
      }
      console.log(line);
    }
  };
  show('Panama', 9, -80); show('Suez', 30, 32); show('Gibraltar', 36, -6); show('Hormuz', 26, 56);
  show('Malacca', 2, 102); show('Bering', 66, -169); show('Cape', -34, 18);
}

mkdirSync('src/shared/geo', { recursive: true });
const b64 = Buffer.from(bits).toString('base64');
writeFileSync(
  'src/shared/geo/mask.ts',
  `// Generated by scripts/build-geo.mjs — do not edit.\n// 360x180 1° cells, row 0 = 90N..89N, col 0 = 180W..179W, bit=1 means land.\nexport const MASK_W = ${W};\nexport const MASK_H = ${H};\nexport const MASK_B64 =\n  '${b64}';\n`,
);
mkdirSync('public/geo', { recursive: true });
copyFileSync('node_modules/world-atlas/land-50m.json', 'public/geo/land-50m.json');
let landCells = 0;
for (let r = 0; r < H; r++) for (let c = 0; c < W; c++) landCells += get(c, r);
console.log(`mask: ${landCells} land cells of ${W * H} (${((100 * landCells) / (W * H)).toFixed(1)}%)`);
